/** Emulator-only end-to-end OSC images: generated bytes travel through the shell PTY, not append(). */
public final class TerminalImageInstrumentation extends Instrumentation {
    private TerminalActivity activity;
    private TerminalView view;
    private TerminalSessions.Job job;
    private File directory;
    private String fixturePath;
    private int cellWidth, cellHeight, screenRows;
    private Bundle launchOptions;

    @Override public void onCreate(Bundle args) {
        PiRuntime.testMode = true;
        fixturePath = args == null ? null : args.getString("fixture_path");
        launchOptions = TerminalWorkspaceInstrumentation.launchOptions(args);
        start();
    }

    @Override public void onStart() {
        Bundle report = new Bundle();
        String failure = "";
        try {
            check(Build.HARDWARE.contains("ranchu") || Build.HARDWARE.contains("goldfish"), "Emulator only");
            runOnMainSync(() -> job = TerminalSessions.get(getTargetContext()).create());
            activity = (TerminalActivity) startActivitySync(new Intent(getTargetContext(), TerminalActivity.class).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK), launchOptions);
            runOnMainSync(() -> view = find(activity.getWindow().getDecorView()));
            check(view != null, "Terminal view missing");
            for (int i = 0; i < 150; i++) {
                runOnMainSync(() -> job = TerminalSessions.get(getTargetContext()).find(view.getCurrentSession()));
                if (job != null && job.id > 0 && job.session.getEmulator() != null) break;
                Thread.sleep(100);
            }
            check(job != null && job.id > 0, "Real shell missing");
            runOnMainSync(() -> {
                cellWidth = (int) view.mRenderer.getFontWidth();
                cellHeight = view.mRenderer.getFontLineSpacing();
                screenRows = emulator().mRows;
            });
            report.putInt("cellWidthPixels", cellWidth);
            report.putInt("cellHeightPixels", cellHeight);
            report.putInt("screenRows", screenRows);
            if (fixturePath != null) {
                check(new File(fixturePath).isFile(), "Fixture does not exist: " + fixturePath);
                command("printf '\\033[?1049l\\033[3J\\033[2J\\033[H'; cat " + quote(fixturePath) + "; printf '\\r\\nOMP_IMAGE_READY\\r\\n'");
                waitText("OMP_IMAGE_READY");
                check(imageCells() > 0, "omp fixture produced no decoded images");
                revealFirstImage();
                saveCapture("terminal-image-omp.png");
                report.putBoolean("realOmpFixtureDecoded", true);
                report.putInt("decodedImageCells", imageCells());
            } else {
                exerciseChecker(report);
            }
        } catch (Throwable error) {
            failure = error.toString();
            report.putString("error", failure);
        } finally {
            runOnMainSync(() -> { if (job != null) job.close(); if (activity != null) activity.finish(); });
            if (directory != null) { File[] files = directory.listFiles(); if (files != null) for (File file : files) file.delete(); directory.delete(); }
        }
        finish(failure.isEmpty() ? -1 : 0, report);
    }

    private void exerciseChecker(Bundle report) throws Exception {
        directory = Files.createTempDirectory(getTargetContext().getCacheDir().toPath(), "terminal-images-").toFile();
        Bitmap checker = Bitmap.createBitmap(256, 128, Bitmap.Config.ARGB_8888);
        Random random = new Random(1337);
        for (int y = 0; y < 128; y++) for (int x = 0; x < 256; x++) {
            int base = y < 64 ? (x < 128 ? 0xffe00000 : 0xff00e000) : (x < 128 ? 0xff0000e0 : 0xffe0e000);
            checker.setPixel(x, y, base | random.nextInt(32) << 16 | random.nextInt(32) << 8 | random.nextInt(32));
        }
        ByteArrayOutputStream png = new ByteArrayOutputStream(), jpeg = new ByteArrayOutputStream();
        checker.compress(Bitmap.CompressFormat.PNG, 100, png);
        checker.compress(Bitmap.CompressFormat.JPEG, 95, jpeg);
        checker.recycle();
        String pngData = Base64.encodeToString(png.toByteArray(), Base64.NO_WRAP);
        String jpegData = Base64.encodeToString(jpeg.toByteArray(), Base64.NO_WRAP);
        check(pngData.length() > 8192, "Checker must exceed normal OSC string limit");
        byte[] oversizedPixels = png.toByteArray();
        ByteBuffer.wrap(oversizedPixels).putInt(16, 8192).putInt(20, 8192);
        CRC32 crc = new CRC32();
        crc.update(oversizedPixels, 12, 17);
        ByteBuffer.wrap(oversizedPixels).putInt(29, (int) crc.getValue());
        File oversizedPayload = new File(directory, "oversized.osc");
        try (FileOutputStream output = new FileOutputStream(oversizedPayload)) {
            output.write("\033]1337;File=inline=1:".getBytes(StandardCharsets.US_ASCII));
            byte[] block = new byte[4096];
            Arrays.fill(block, (byte) 'A');
            int remaining = ((8 * 1024 * 1024 + 2) / 3) * 4 + 4;
            while (remaining > 0) { int count = Math.min(block.length, remaining); output.write(block, 0, count); remaining -= count; }
            output.write(7);
        }
        int widthPixels = 16 * cellWidth;
        StringBuilder script = new StringBuilder("#!/system/bin/sh\nprintf '\\033[?1049l\\033[3J\\033[2J\\033[H\\033[?25l\\033[2;3H'\n");
        fragmented(script, osc("inline=1;width=16;height=auto", pngData, false));
        script.append("printf '\\r\\nIMAGE_READY\\r\\n'\n");
        gate(script, "history");
        script.append("i=0; while [ $i -lt ").append(screenRows + 4).append(" ]; do printf 'HISTORY_%03d\\r\\n' $i; i=$((i+1)); done\nprintf 'HISTORY_READY\\r\\n'\n");
        gate(script, "alt");
        script.append("printf '\\033[?1049hALT_EMPTY'\n");
        gate(script, "altimage");
        script.append("printf '\\033[2J\\033[H'\n");
        fragmented(script, osc("inline=1;width=auto;height=auto", pngData, true));
        script.append("printf '\\r\\nALT_IMAGE\\r\\n'\n");
        gate(script, "main");
        script.append("printf '\\033[?1049lMAIN_RETURN\\r\\n'\n");
        gate(script, "erase");
        script.append("printf '\\033[3J\\033[2J\\033[HERASED'\n");
        gate(script, "invalid");
        literal(script, osc("inline=0", pngData, false));
        literal(script, osc("width=16", pngData, false));
        literal(script, osc("inline=1;width=0", pngData, false));
        literal(script, osc("inline=1;size=8388609", pngData, false));
        literal(script, osc("inline=1;size=4", pngData, false));
        literal(script, osc("inline=1", "A===", false));
        literal(script, osc("inline=1", "AAAA!AAA", true));
        literal(script, osc("inline=1;name=" + "x".repeat(2048), pngData, false));
        literal(script, osc("inline=1", Base64.encodeToString(oversizedPixels, Base64.NO_WRAP), false));
        script.append("cat ").append(quote(oversizedPayload.toString())).append('\n');
        script.append("printf '\\r\\nINVALID_READY\\r\\n'\n");
        gate(script, "jpeg");
        script.append("printf '\\033[2J\\033[H\\033[2;3H'\n");
        fragmented(script, osc("inline=1;width=160px;height=80px", jpegData, true));
        script.append("printf '\\r\\nJPEG_READY\\r\\n'\n");
        gate(script, "overwrite");
        script.append("printf '\\033[2;3H\\033[2KOVERWRITTEN'\n");
        gate(script, "reset");
        script.append("printf '\\033cRESET_READY'\n");
        File shell = new File(directory, "images.sh");
        Files.writeString(shell.toPath(), script.toString(), StandardCharsets.UTF_8);
        command("/system/bin/sh " + quote(shell.toString()));
        waitText("IMAGE_READY");
        check(imageCells() > 0, "Fragmented PNG did not decode");
        assertChecker(widthPixels, widthPixels / 2f);
        saveCapture("terminal-image-checker.png");
        report.putBoolean("fragmentedPngPixelsAndAspect", true);
        int retainedCells = imageCells();
        signal("history"); waitText("HISTORY_READY");
        check(imageCells() == retainedCells, "Image cells lost during scroll into history");
        revealFirstImage(); assertChecker(widthPixels, widthPixels / 2f);
        check(topRow() < 0, "Image was not rendered through manual history viewport");
        report.putBoolean("historyViewportPixels", true);
        runOnMainSync(() -> view.setTopRow(0));
        signal("alt"); waitText("ALT_EMPTY");
        check(imageCells() == 0, "Main image leaked into alternate screen");
        signal("altimage"); waitText("ALT_IMAGE");
        check(imageCells() > 0, "ST terminated native PNG did not decode");
        assertChecker(256, 128);
        report.putBoolean("nativeSizingAndStringTerminator", true);
        signal("main"); waitText("MAIN_RETURN");
        check(imageCells() == retainedCells, "Alternate image leaked into main screen");
        signal("erase"); waitText("ERASED");
        check(imageCells() == 0, "Erase screen/history retained image cells");
        signal("invalid"); waitText("INVALID_READY");
        check(imageCells() == 0, "Malformed/unsupported transfer was accepted");
        report.putBoolean("malformedAndMetadataLimits", true);
        signal("jpeg"); waitText("JPEG_READY");
        assertChecker(160, 80);
        report.putBoolean("jpegExactPixelSizing", true);
        int beforeErase = imageCells();
        signal("overwrite"); waitText("OVERWRITTEN");
        check(imageCells() < beforeErase, "Erase line left image covering replaced text");
        signal("reset"); waitText("RESET_READY");
        check(imageCells() == 0, "Terminal reset retained image placements");
        report.putBoolean("eraseAlternateAndResetOwnership", true);
    }

    private void fragmented(StringBuilder script, String sequence) {
        // Force header/base64 fragmentation and ESC/ST separation through distinct real PTY writes.
        boolean st = sequence.endsWith("\033\\");
        int end = st ? sequence.length() - 2 : sequence.length();
        for (int offset = 0, chunk = 0; offset < end; offset += 193, chunk++) {
            literal(script, sequence.substring(offset, Math.min(end, offset + 193)));
            if (chunk % 31 == 0) script.append("sleep 0.01\n");
        }
        if (st) script.append("printf '\\033'; sleep 0.02; printf '\\\\'\n");
    }

    private static String osc(String header, String data, boolean st) { return "\033]1337;File=" + header + ":" + data + (st ? "\033\\" : "\007"); }
    private static String quote(String text) { return "'" + text.replace("'", "'\\''") + "'"; }
    private static void literal(StringBuilder script, String value) { script.append("printf '%s' ").append(quote(value)).append('\n'); }
    private void gate(StringBuilder script, String name) { script.append("while [ ! -f ").append(quote(new File(directory, name).toString())).append(" ]; do sleep 0.05; done\n"); }
    private void signal(String name) throws Exception { Files.writeString(new File(directory, name).toPath(), "go"); }
    private void command(String text) { runOnMainSync(() -> view.onCreateInputConnection(new EditorInfo()).commitText(text + "\n", 1)); }
    private TerminalEmulator emulator() { return job.session.getEmulator(); }
    private int topRow() { int[] value = {0}; runOnMainSync(() -> value[0] = view.getTopRow()); return value[0]; }
    private int imageCells() {
        int[] count = {0};
        runOnMainSync(() -> {
            TerminalBuffer screen = emulator().getScreen();
            for (int y = -screen.getActiveTranscriptRows(); y < emulator().mRows; y++) {
                TerminalRow row = screen.allocateFullLineIfNecessary(screen.externalToInternalRow(y));
                for (int x = 0; x < emulator().mColumns; x++) { TerminalImage image = row.getImage(x); if (image != null && image.bitmap != null) count[0]++; }
            }
        });
        return count[0];
    }
    private void revealFirstImage() {
        runOnMainSync(() -> {
            TerminalBuffer screen = emulator().getScreen();
            for (int y = -screen.getActiveTranscriptRows(); y < emulator().mRows; y++) {
                TerminalRow row = screen.allocateFullLineIfNecessary(screen.externalToInternalRow(y));
                for (int x = 0; x < emulator().mColumns; x++) if (row.getImage(x) != null && row.getImage(x).bitmap != null) {
                    view.setTopRow(Math.min(0, Math.max(-screen.getActiveTranscriptRows(), y - 1))); view.invalidate(); return;
                }
            }
        });
    }
    private Bitmap capture() {
        AtomicReference<Bitmap> result = new AtomicReference<>();
        runOnMainSync(() -> { Bitmap bitmap = Bitmap.createBitmap(view.getWidth(), view.getHeight(), Bitmap.Config.ARGB_8888); view.draw(new Canvas(bitmap)); result.set(bitmap); });
        return result.get();
    }
    private void saveCapture(String name) throws Exception {
        Bitmap bitmap = capture();
        try (FileOutputStream output = new FileOutputStream(new File(getTargetContext().getExternalFilesDir(null), name))) { bitmap.compress(Bitmap.CompressFormat.PNG, 100, output); }
        finally { bitmap.recycle(); }
    }
    private void assertChecker(float expectedWidth, float expectedHeight) {
        Bitmap bitmap = capture();
        int left = bitmap.getWidth(), top = bitmap.getHeight(), right = -1, bottom = -1;
        int[] quadrants = new int[4];
        for (int y = 0; y < bitmap.getHeight(); y++) for (int x = 0; x < bitmap.getWidth(); x++) {
            int color = bitmap.getPixel(x, y), r = Color.red(color), g = Color.green(color), b = Color.blue(color);
            int kind = r > 160 && g < 100 && b < 100 ? 0 : r < 100 && g > 160 && b < 100 ? 1 : r < 100 && g < 100 && b > 160 ? 2 : r > 160 && g > 160 && b < 100 ? 3 : -1;
            if (kind >= 0) { quadrants[kind]++; left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y); }
        }
        bitmap.recycle();
        for (int count : quadrants) check(count > 25, "Checker quadrant was not rendered");
        check(Math.abs(right - left + 1 - expectedWidth) <= 2, "Rendered width differs: " + (right - left + 1) + " expected " + expectedWidth);
        check(Math.abs(bottom - top + 1 - expectedHeight) <= 2, "Rendered height/aspect differs: " + (bottom - top + 1) + " expected " + expectedHeight);
    }
    private void waitText(String text) throws Exception {
        for (int i = 0; i < 1200; i++) {
            AtomicReference<String> output = new AtomicReference<>();
            runOnMainSync(() -> output.set(emulator().getScreen().getTranscriptText()));
            if (output.get().contains(text)) return;
            Thread.sleep(50);
        }
        throw new IllegalStateException("Missing real PTY output: " + text);
    }
    private static TerminalView find(View root) {
        if (root instanceof TerminalView) return (TerminalView) root;
        if (root instanceof ViewGroup) for (int i = 0; i < ((ViewGroup) root).getChildCount(); i++) { TerminalView found = find(((ViewGroup) root).getChildAt(i)); if (found != null) return found; }
        return null;
    }
    private static void check(boolean value, String message) { if (!value) throw new IllegalStateException(message); }
}
